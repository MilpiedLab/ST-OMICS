# Activate current assay (sample id layer)
xenium_data = activateSeuratAssay(xenium_data, 
                                  ident = "SAMPLE_ID", 
                                  active_assay = XENIUM_ASSAY_NAME)

# Init list to store data subsets with banksy embeddings
banksy_subsets = list()

# Iterate over available samples in merged data
for (sample in unique(xenium_data@meta.data[["SAMPLE_ID"]])){
  
  cat("\n\n")
  cat(sprintf("%s %s", strrep("#", 2), sample), " {.tabset .tabset-fade}\n\n")
  cat("\n\n")
  
  #################
  ## 1.1. SUBSET ##
  #################
  
  # Subset current sample from global merged data
  sample_subset = subset(xenium_data,
                         subset = seurat_clusters == sample)
  
  #################
  ## 1.2. BANKSY ##
  #################
  
  # Banksy neighborhood analysis for current sample
  sample_subset = banksy_neighborhood_analysis(seurat_object = sample_subset,
                                               lambda = LAMBDA,
                                               active_assay = XENIUM_ASSAY_NAME,
                                               active_slot = "data",
                                               k_geom = K_GEOM,
                                               banksy_assay_name = BANKSY_ASSAY_NAME,
                                               dimension_principal_component_analysis = DIM_PCA,
                                               dimension_clustering = DIM_USE,
                                               umap_layer_name = paste0("UMAP_", BANKSY_ASSAY_NAME),
                                               resolution_range = RES_RANGE)
  
  # Store subset for later merging
  banksy_subsets[[sample]] = sample_subset
  
  ####################
  ## 1.3. PLOT DATA ##
  ####################
  
  # Iterate over resolutions covered
  for (res in RES_RANGE){
    
    # Define current neighborhood cluster layer
    temp_neighborhood_cluster_layer = sprintf("%s_snn_res.%s", 
                                              BANKSY_ASSAY_NAME, 
                                              res)
    
    # Activate current neighborhood cluster layer
    sample_subset = activateSeuratAssay(sample_subset, 
                                        ident = temp_neighborhood_cluster_layer, 
                                        active_assay = XENIUM_ASSAY_NAME)
    
    ###############################
    ## 1.3.1. DISPLAY WHOLE DATA ##
    ###############################
    
    cat("\n\n")
    cat(sprintf("%s %s", strrep("#", 3), res), " {.tabset .tabset-fade}\n\n")
    cat("\n\n")
    
    cat("\n\n")
    cat(sprintf("%s Clusters", strrep("#", 4)))
    cat("\n\n")
    
    cat("\n\n")
    print(DimPlot(sample_subset,
                  cols = COLOR_PALETTE,
                  label = TRUE) +
            ggtitle(sprintf("%s Banksy clusters (lambda %s)", sample, LAMBDA)))
    cat("\n\n")
    
    cat("\n\n")
    cat(sprintf("%s Tissue", strrep("#", 4)))
    cat("\n\n")
    
    # Display tissue view
    cat("\n\n")
    print(ImageDimPlot(sample_subset, 
                       cols = COLOR_PALETTE, 
                       size = 0.75) + 
            ggtitle(sprintf("%s Banksy neighborhoods (lambda %s)", sample, LAMBDA)) +
            labs(fill = sprintf("res = %s, λ = %s", res, LAMBDA)))
    cat("\n\n")
    
    #############################################
    ## 1.3.2. DISPLAY INDIVIDUAL NEIGHBORHOODS ##
    #############################################

    # Display each neighborhood from current condition
    for (neighborhood in 0:(length(unique(sample_subset$seurat_clusters))-1)){
      
      # Subset cells part of current neighborhood
      temp_neighborhood_subset = subset(sample_subset, subset = seurat_clusters == neighborhood)
      
      cat("\n\n")
      cat(sprintf("%s %s", strrep("#", 4), neighborhood))
      cat("\n\n")
      
      # Display neighborhood tissue view
      cat("\n\n")
      print(ImageDimPlot(temp_neighborhood_subset, 
                         size = 0.75) + 
              ggtitle(sprintf("%s Banksy neighborhood %s (res = %s)", sample, neighborhood, res)) +
              labs(fill = sprintf("res = %s", res)))
      cat("\n\n")
      
    }
  }
}

